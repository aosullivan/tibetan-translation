"""
Tibetan File Handler extending the base FileHandler for Tibetan-specific operations.
Handles "/" delimited parsing and Unicode-aware file writing for Tibetan script.
"""

import logging
import traceback
from typing import List, Dict, Any
from .file_handler import FileHandler
from .config import TibetanConfig as cfg
from .tibetan_line_parser import TibetanLineParser, TibetanLine
from .tibetan_output_formatter import TibetanOutputFormatter, ProcessedLine, ProcessingStatus

logger = logging.getLogger(__name__)


# ProcessedLine is now imported from tibetan_output_formatter


class TibetanFileHandler(FileHandler):
    """
    Extended FileHandler for Tibetan text processing with "/" delimiter parsing
    and Unicode-aware file operations.
    """
    
    def __init__(self):
        super().__init__()
        self.parser = TibetanLineParser()
        self.formatter = TibetanOutputFormatter()
        self.processed_lines: List[ProcessedLine] = []
    
    def read_wylie_file(self, file_path: str) -> List[TibetanLine]:
        """
        Read and parse a Wylie file with "/" delimiter parsing.
        
        Args:
            file_path: Path to the Wylie input file
            
        Returns:
            List of parsed TibetanLine objects
            
        Raises:
            FileNotFoundError: If input file doesn't exist
            Exception: For other file reading errors
        """
        try:
            logger.info(f"Reading Wylie file: {file_path}")
            
            # Use the TibetanLineParser to parse the file
            tibetan_lines = self.parser.parse_file(file_path)
            
            logger.info(f"Successfully parsed {len(tibetan_lines)} lines from {file_path}")
            
            # Filter out empty lines if configured to do so
            if cfg.SKIP_EMPTY_LINES:
                tibetan_lines = [line for line in tibetan_lines if line.wylie_content.strip()]
                logger.info(f"After filtering empty lines: {len(tibetan_lines)} lines remain")
            
            return tibetan_lines
            
        except FileNotFoundError as e:
            logger.error(f"Wylie file {file_path} not found: {str(e)}")
            raise
        except Exception as e:
            logger.error(f"Error reading Wylie file: {str(e)}\n{traceback.format_exc()}")
            raise
    
    def write_tibetan_output(self, output_path: str, processed_lines: List[ProcessedLine], 
                           use_structured_format: bool = True) -> None:
        """
        Write processed Tibetan lines to output file with proper Unicode encoding.
        
        Args:
            output_path: Path to the output file
            processed_lines: List of ProcessedLine objects to write
            use_structured_format: Whether to use the new structured output format
            
        Raises:
            Exception: For file writing errors
        """
        try:
            logger.info(f"Writing Tibetan output to: {output_path}")
            
            with open(output_path, 'w', encoding=cfg.UNICODE_ENCODING) as f:
                if use_structured_format:
                    # Use the new structured output formatter
                    structured_output = self.formatter.generate_structured_output(
                        processed_lines, 
                        "Tibetan Text Processing Results"
                    )
                    f.write(structured_output)
                else:
                    # Use the legacy format for backward compatibility
                    self._write_legacy_format(f, processed_lines)
            
            logger.info(f"Successfully wrote {len(processed_lines)} processed lines to {output_path}")
            
        except Exception as e:
            logger.error(f"Error writing Tibetan output: {str(e)}\n{traceback.format_exc()}")
            raise
    
    def _write_legacy_format(self, file_handle, processed_lines: List[ProcessedLine]) -> None:
        """Write output in the legacy format for backward compatibility."""
        # Write header
        file_handle.write("# Tibetan Text Processing Output\n\n")
        file_handle.write("Generated by Tibetan Text Processor\n\n")
        file_handle.write("---\n\n")
        
        # Write processed lines in three-column format
        for processed_line in processed_lines:
            formatted_line = self.formatter.format_triple_output(processed_line)
            if formatted_line.strip():
                file_handle.write(formatted_line)
        
        # Write summary
        summary_report = self.formatter.generate_summary_report(processed_lines)
        file_handle.write(summary_report)
    
    def ensure_unicode_support(self, content: str) -> str:
        """
        Ensure content is properly encoded for Unicode Tibetan script.
        
        Args:
            content: Text content to check/fix
            
        Returns:
            Unicode-safe content
        """
        if not content:
            return content
        
        try:
            # Ensure the content can be encoded/decoded properly
            encoded = content.encode(cfg.UNICODE_ENCODING)
            decoded = encoded.decode(cfg.UNICODE_ENCODING)
            return decoded
        except UnicodeError as e:
            logger.warning(f"Unicode encoding issue: {str(e)}")
            # Fallback: replace problematic characters
            return content.encode(cfg.UNICODE_ENCODING, errors='replace').decode(cfg.UNICODE_ENCODING)
    
    def initialize_tibetan_output_files(self) -> None:
        """Initialize all Tibetan-specific output files."""
        try:
            # Initialize main output file
            with open(cfg.OUTPUT_FILE, 'w', encoding=cfg.UNICODE_ENCODING) as f:
                f.write("# Tibetan Text Processing Output\n\n")
                f.write("Processing started...\n\n")
            
            # Initialize separate output files if configured
            if hasattr(cfg, 'WYLIE_OUTPUT_FILE'):
                with open(cfg.WYLIE_OUTPUT_FILE, 'w', encoding=cfg.UNICODE_ENCODING) as f:
                    f.write("# Wylie Transliteration Output\n\n")
            
            if hasattr(cfg, 'PHONETIC_OUTPUT_FILE'):
                with open(cfg.PHONETIC_OUTPUT_FILE, 'w', encoding=cfg.UNICODE_ENCODING) as f:
                    f.write("# Phonetic Rendering Output\n\n")
            
            if hasattr(cfg, 'TRANSLATION_OUTPUT_FILE'):
                with open(cfg.TRANSLATION_OUTPUT_FILE, 'w', encoding=cfg.UNICODE_ENCODING) as f:
                    f.write("# English Translation Output\n\n")
            
            logger.info("Initialized Tibetan output files")
            
        except Exception as e:
            logger.error(f"Error initializing Tibetan output files: {str(e)}")
            raise
    
    def save_tibetan_progress(self, processed_lines: List[ProcessedLine]) -> None:
        """
        Save processing progress for Tibetan lines.
        
        Args:
            processed_lines: List of processed lines to save
        """
        try:
            # Update progress tracking
            for processed_line in processed_lines:
                line_key = f"line_{processed_line.source_line.line_number}"
                self.progress[line_key] = (processed_line.processing_status == ProcessingStatus.SUCCESS)
            
            # Save progress using parent method
            self.save_progress()
            
            # Also save intermediate results if enabled
            if cfg.ENABLE_PROGRESS_SAVING:
                self.write_tibetan_output(cfg.OUTPUT_FILE, processed_lines)
            
            logger.info(f"Saved progress for {len(processed_lines)} processed lines")
            
        except Exception as e:
            logger.error(f"Error saving Tibetan progress: {str(e)}")
            raise
    
    def create_processed_line(self, source_line: TibetanLine) -> ProcessedLine:
        """
        Create a ProcessedLine object from a TibetanLine.
        
        Args:
            source_line: TibetanLine object to wrap
            
        Returns:
            ProcessedLine object ready for processing
        """
        return ProcessedLine(source_line=source_line)